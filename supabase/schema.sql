create table if not exists public.repair_requests (
  id bigint generated by default as identity primary key,
  full_name text not null,
  phone text not null,
  email text,
  drone_brand text not null,
  drone_model text,
  problem_type text not null,
  problem_description text not null,
  repair_requirement text,
  pickup_preference text,
  damage_photos jsonb not null default '[]'::jsonb,
  status text not null default 'new' check (status in ('new', 'reviewing', 'quoted', 'in_repair', 'completed', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.repair_requests enable row level security;

insert into storage.buckets (id, name, public)
values ('repair-damage-photos', 'repair-damage-photos', false)
on conflict (id) do nothing;
